// Small helpers shared by the scene modules. Brand colours only (see docs/ARCHITECTURE.md).
import * as THREE from 'three';

export const HEX = { lime: '#ccff00', white: '#ffffff', ink: '#111111', black: '#000000', red: '#ff3d2e' };

export function makePalette() {
  return Object.fromEntries(Object.entries(HEX).map(([k, v]) => [k, new THREE.Color(v)]));
}

export const clamp01 = (x) => Math.min(Math.max(x, 0), 1);
export const easeOut = (x) => 1 - Math.pow(1 - clamp01(x), 3);
export const easeInOut = (x) => { x = clamp01(x); return x * x * (3 - 2 * x); };

export function edges(geo, color = HEX.white, opacity = 0.35) {
  return new THREE.LineSegments(new THREE.EdgesGeometry(geo), new THREE.LineBasicMaterial({ color, transparent: true, opacity }));
}

export const metal = (color, extra = {}) => new THREE.MeshStandardMaterial({ color, roughness: 0.35, metalness: 0.55, ...extra });

// Floating dust: a cube of tiny white points.
export function dust(count, spread, color = HEX.white, size = 0.018) {
  const pos = new Float32Array(count * 3);
  for (let i = 0; i < count * 3; i++) pos[i] = (Math.random() - 0.5) * spread;
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
  return new THREE.Points(g, new THREE.PointsMaterial({ color, size, transparent: true, opacity: 0.55, sizeAttenuation: true }));
}

// Dispose every geometry/material/texture under an object.
export function disposeTree(obj) {
  obj.traverse((o) => {
    o.geometry?.dispose?.();
    const mats = Array.isArray(o.material) ? o.material : o.material ? [o.material] : [];
    for (const m of mats) {
      for (const v of Object.values(m)) if (v && v.isTexture) v.dispose();
      m.dispose();
    }
  });
}

