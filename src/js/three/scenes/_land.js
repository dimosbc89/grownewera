// -> Uint8Array(w * h), 1 = land, row-major from the north-west corner.
export function decodeMask({ w, h, data }) {
  const bin = atob(data);
  const out = new Uint8Array(w * h);
  let p = 0;
  for (let row = 0, i = 0; row < h; row++) {
    let x = 0;
    let land = 0;
    while (x < w) {
      let n = 0;
      let shift = 0;
      let b;
      do { b = bin.charCodeAt(i++); n |= (b & 0x7f) << shift; shift += 7; } while (b & 0x80);
      if (land) out.fill(1, p + x, p + x + n);
      x += n;
      land ^= 1;
    }
    p += w;
  }
  return out;
}
