#!/usr/bin/env node
// Build-time tool: outlines of the CTA wordmark ("GROW.") from the brand font, as SVG path data
// for src/js/three/wordmark.js (SVGLoader -> ExtrudeGeometry at runtime). The output is committed,
// so the site build never needs the font parser; re-run this only to change the text or weight.
//
//   npm i -D opentype.js @fontsource/space-grotesk   (devDependencies, already in package.json)
//   node tools/wordmark-glyphs.mjs [--text "GROW."] [--weight 700] [--out src/js/three/wordmark-glyphs.json]
//
// Space Grotesk ships as a variable font on the site; opentype.js reads the static WOFF instances
// of @fontsource/space-grotesk (same outlines at the named weight). Coordinates are in font units
// scaled to 1000/em, y down (SVG), baseline at y = 0, each glyph at its own origin (`x` is its pen
// position in the word, kerning and tracking applied).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const text = arg('text', 'GROW.');
const weight = arg('weight', '700');
const tracking = Number(arg('tracking', '-0.012')); // em, like the site's tight display headings
const out = resolve(process.cwd(), arg('out', resolve(root, 'src/js/three/wordmark-glyphs.json')));

const require = createRequire(import.meta.url);
let opentype;
try {
  opentype = require('opentype.js');
} catch {
  console.error('opentype.js is missing: run `npm install` (it is a devDependency).');
  process.exit(1);
}
let fontFile;
try {
  fontFile = require.resolve(`@fontsource/space-grotesk/files/space-grotesk-latin-${weight}-normal.woff`);
} catch {
  console.error(`@fontsource/space-grotesk (weight ${weight}) is missing: run \`npm install\`.`);
  process.exit(1);
}

const buf = readFileSync(fontFile);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const scale = 1000 / font.unitsPerEm;
const r = (v) => Math.round(v * 10) / 10;

// Path commands -> compact SVG path data (absolute, one decimal). Zero-length line segments
// (opentype.js emits one after every contour start) are dropped.
function pathData(commands) {
  let at = '';
  return commands.map((c) => {
    const to = c.x === undefined ? '' : `${r(c.x)} ${r(c.y)}`;
    if (c.type === 'L' && to === at) return '';
    if (to) at = to;
    switch (c.type) {
      case 'M': case 'L': return `${c.type}${to}`;
      case 'Q': return `Q${r(c.x1)} ${r(c.y1)} ${to}`;
      case 'C': return `C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${to}`;
      case 'Z': return 'Z';
      default: throw new Error(`unknown path command ${c.type}`);
    }
  }).join('');
}

const glyphs = [];
let pen = 0;
let prev = null;
for (const char of text) {
  const g = font.charToGlyph(char);
  if (!g || g.index === 0) throw new Error(`"${char}" is not in the font`);
  if (prev) pen += font.getKerningValue(prev, g) * scale;
  const path = g.getPath(0, 0, 1000); // font size 1000 -> units of 1/1000 em, y down
  const bb = path.getBoundingBox();
  glyphs.push({
    char,
    x: r(pen),
    advance: r(g.advanceWidth * scale),
    bbox: [r(bb.x1), r(bb.y1), r(bb.x2), r(bb.y2)],
    d: pathData(path.commands),
  });
  pen += g.advanceWidth * scale + tracking * 1000;
  prev = g;
}
const last = glyphs[glyphs.length - 1];
const os2 = font.tables.os2 ?? {};
const data = {
  source: `Space Grotesk ${weight} (@fontsource/space-grotesk, ${relative(root, fontFile).split('/').pop()}), generated by tools/wordmark-glyphs.mjs`,
  text,
  unitsPerEm: 1000,
  capHeight: r((os2.sCapHeight || 700 * font.unitsPerEm / 1000) * scale),
  ascender: r(font.ascender * scale),
  descender: r(font.descender * scale),
  width: r(last.x + last.bbox[2]),
  glyphs,
};
// One glyph per line keeps the committed file small and its diffs readable.
const json = JSON.stringify({ ...data, glyphs: [] }, null, 1)
  .replace('"glyphs": []', `"glyphs": [\n${glyphs.map((g) => `  ${JSON.stringify(g)}`).join(',\n')}\n ]`);
writeFileSync(out, `${json}\n`);
console.log(`${text}: ${glyphs.length} glyphs, ${data.width} units wide -> ${relative(process.cwd(), out)}`);
